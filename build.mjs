/**
 * Build the browser bundle.
 *
 * The client module system only allows self-contained chunks: a bundle may
 * require platform modules (react, react-dom, …) but must not synchronously
 * require a sibling file. So the deterministic core (src/rules.cjs) is inlined
 * here rather than imported at runtime.
 *
 *   node build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const rulesSource = fs
  .readFileSync(path.join(root, 'src', 'rules.cjs'), 'utf8')
  .replace(/module\.exports = api;\s*$/, 'var AskRules = api;');

if (!/var AskRules = api;/.test(rulesSource)) {
  throw new Error('build: could not rewrite rules.cjs export');
}

const uiSource = fs.readFileSync(path.join(root, 'src', 'ui.js'), 'utf8');

const body = [
  '    var React = require("react");',
  '    var ReactDOM = require("react-dom");',
  '    var h = React.createElement;',
  '',
  '    // ---- inlined src/rules.cjs ----',
  rulesSource,
  '',
  '    // ---- inlined src/ui.js ----',
  uiSource,
  '',
  '    exports.apply = apply;',
  '    exports.inject = ["slots"];',
  '    return module.exports;'
].join('\n');

const bundle = [
  '// Generated by build.mjs — do not edit directly.',
  '// Sources: src/rules.cjs + src/ui.js',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  body,
  '  }',
  '});',
  ''
].join('\n');

const outFile = path.join(root, 'lib', 'client.js');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, bundle, 'utf8');

const bytes = Buffer.byteLength(bundle, 'utf8');
console.log('built', path.relative(root, outFile), '→', bytes, 'bytes');
